pub trait TriuAPI<Inp> {
    type Out;

    fn triu_f(self) -> Result<Self::Out>;

    fn triu(self) -> Self::Out
    where
        Self: Sized,
    {
        Self::triu_f(self).rstsr_unwrap()
    }
}

/// Returns the upper triangular part of a matrix (or a stack of matrices) x.
///
/// Elements below the k-th diagonal are zeroed, where `k = 0` selects the
/// main diagonal, positive `k` is above it, and negative `k` is below it. The
/// other elements are kept unchanged. For [`TensorView`] input, the result is
/// an owned tensor, contiguous in the device default order; the logical
/// content does not depend on the order.
///
/// This function behaves identically under [`RowMajor`] and [`ColMajor`] device default orders.
///
/// # Overloads Table
///
/// - `triu((x: TensorView<'_, T, B, D>, k: isize)) -> Tensor<T, B, D>` (copy, then zero)
/// - `triu(x: TensorView<'_, T, B, D>) -> Tensor<T, B, D>` (implicit `k = 0`)
/// - `triu((x: TensorMut<'_, T, B, D>, k: isize)) -> TensorMut<'_, T, B, D>` (in place)
/// - `triu(x: TensorMut<'_, T, B, D>) -> TensorMut<'_, T, B, D>` (implicit `k = 0`)
/// - `triu((x: Tensor<T, B, D>, k: isize)) -> Tensor<T, B, D>` (in place)
/// - `triu(x: Tensor<T, B, D>) -> Tensor<T, B, D>` (implicit `k = 0`)
/// - `triu((x: &TensorAny<R, T, B, D>, k: isize)) -> Tensor<T, B, D>` (same as view)
/// - `triu(x: &TensorAny<R, T, B, D>) -> Tensor<T, B, D>` (same as view)
///
/// # Parameters
///
/// - `x`: input tensor of shape `(..., M, N)`: a matrix, or a stack of matrices on the last two
///   axes.
/// - `k`: diagonal index; defaults to `0` if omitted.
///
/// # Returns
///
/// - `Tensor<T, B, D>` (or [`TensorMut<'_, T, B, D>`][`TensorMut`] for the mutable-input
///   overloads): tensor with the upper triangular part of `x` (elements below the k-th diagonal are
///   replaced by zero). Whether the result is a new tensor or the mutated input depends on the
///   ownership form of `x`, as for [`tril`].
///
/// # Examples
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(RowMajor);
/// let a = rt::arange((1, 10, &device)).into_shape([3, 3]);
/// println!("{}", rt::triu((&a, 0)));
/// // [[ 1 2 3]
/// //  [ 0 5 6]
/// //  [ 0 0 9]]
/// # assert_eq!(format!("{}", rt::triu((&a, 0))), "[[ 1 2 3]\n [ 0 5 6]\n [ 0 0 9]]");
/// ```
///
/// # Notes of API accordance
///
/// - Array-API: `triu(x, /, *, k=0)` ([`triu`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.triu.html))
/// - NumPy: `numpy.triu(m, k=0)` ([`numpy.triu`](https://numpy.org/doc/stable/reference/generated/numpy.triu.html))
/// - RSTSR: `rt::triu((x, k))`; ownership forms are overloaded instead of always returning a new
///   tensor.
///
/// # Panics
///
/// - Panics if the input has fewer than 2 dimensions.
///
/// For a fallible version, use [`triu_f`].
///
/// # See also
///
/// ## Similar function from other crates/libraries
///
/// - Python Array API standard: [`triu`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.triu.html)
/// - NumPy: [`numpy.triu`](https://numpy.org/doc/stable/reference/generated/numpy.triu.html)
/// - PyTorch: [`torch.triu`](https://docs.pytorch.org/docs/stable/generated/torch.triu.html)
///
/// ## Related functions in RSTSR
///
/// - [`tril`]: lower triangular part.
/// - [`eye`]: tensor with ones on the k-th diagonal.
///
/// ## Variants of this function
///
/// - [`triu_f`]: fallible version.
pub fn triu<Args, Inp>(param: Args) -> Args::Out
where
    Args: TriuAPI<Inp>,
{
    return TriuAPI::triu(param);
}

/// Returns the upper triangular part of a matrix (or a stack of matrices) x.
