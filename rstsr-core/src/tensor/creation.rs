/// New tensor having a specified shape and filled with given value.
///
/// <div class="warning">
///
/// **Row/Column Major Notice**
///
/// This function behaves differently on default orders ([`RowMajor`] and [`ColMajor`]) of device.
///
/// </div>
///
/// The returned tensor is C-contiguous or F-contiguous according to the device
/// default order (or an explicitly specified `order`). Passing a [`Layout`]
/// instead of a shape pins the exact layout and bypasses this behavior. See
/// [`order_semantics`](crate::order_semantics) for a discussion of the two orders.
///
/// # Overloads Table
///
/// Output is [`Tensor<T, B, IxD>`][`Tensor`]; `fill_value` has type `T`.
///
/// - `full((shape: D, fill_value: T, device: &B)) -> Tensor<T, B, IxD>`
/// - `full((shape: D, fill_value: T, order: FlagOrder, device: &B)) -> Tensor<T, B, IxD>`
/// - `full((layout: Layout<D>, fill_value: T, device: &B)) -> Tensor<T, B, IxD>` (use the exact
///   layout)
///
/// Also, overloads without the device argument behave the same and create the
/// tensor on [`DeviceCpu::default()`]:
///
/// - `full((shape: D, fill_value: T, order: FlagOrder)) -> Tensor<T, DeviceCpu, IxD>`
/// - `full((shape: D, fill_value: T)) -> Tensor<T, DeviceCpu, IxD>`
/// - `full((layout: Layout<D>, fill_value: T)) -> Tensor<T, DeviceCpu, IxD>`
///
/// # Parameters
///
/// - `shape`: shape of the new tensor, anything that converts into [`AxesIndex<isize>`][AxesIndex].
///   - Overloads:
///     - integer: 1-D shape with a single dimension.
///     - vector/array/tuple of integers: N-D shape with N dimensions.
/// - `fill_value`: the value to fill the tensor with.
/// - `order`: [`FlagOrder`] ([`RowMajor`] or [`ColMajor`]): contiguity of the new tensor. Defaults
///   to the device default order if omitted.
/// - `layout`: [`Layout<D>`][`Layout`]: exact layout (shape, stride, and offset) of the new tensor.
/// - `device`: the device to create the tensor on.
///
/// # Returns
///
/// - [`Tensor<T, B, IxD>`][`Tensor`]: tensor filled with `fill_value`, owning its data.
///
/// # Examples
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(RowMajor);
/// let f: Tensor<i32, _> = rt::full(([2, 2], 7, &device));
/// println!("{f}");
/// // [[ 7 7]
/// //  [ 7 7]]
/// # assert_eq!(f.shape(), &[2, 2]);
/// ```
///
/// ## Difference between [`RowMajor`] and [`ColMajor`]
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(ColMajor);
/// let f: Tensor<i32, _> = rt::full(([2, 3], 7, &device));
/// println!("{:?}", f.layout());
/// // 2-Dim (dyn), contiguous: Ff
/// // shape: [2, 3], stride: [1, 2], offset: 0
/// # assert_eq!(format!("{:?}", f.layout()), "2-Dim (dyn), contiguous: Ff\nshape: [2, 3], stride: [1, 2], offset: 0");
/// ```
///
/// # Notes of API accordance
///
/// - Array-API: `full(shape, fill_value, /, *, dtype=None, device=None)` ([`full`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.full.html))
/// - NumPy: `numpy.full(shape, fill_value, dtype=None, order='C')` ([`numpy.full`](https://numpy.org/doc/stable/reference/generated/numpy.full.html))
/// - RSTSR: `rt::full((shape, fill_value, order, &device))`; the dtype follows `fill_value` (or the
///   type annotation), and `order` participates in the tuple overload.
///
/// # Panics
///
/// - Panics if the provided [`Layout`] is invalid (out-of-bound bounds).
///
/// For a fallible version, use [`full_f`].
///
/// # See also
///
/// ## Similar function from other crates/libraries
///
/// - Python Array API standard: [`full`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.full.html)
/// - NumPy: [`numpy.full`](https://numpy.org/doc/stable/reference/generated/numpy.full.html)
///
/// ## Related functions in RSTSR
///
/// - [`full_like`]: fill with the shape of another tensor.
/// - [`zeros`] / [`ones`]: tensor filled with zeros / ones.
///
/// ## Variants of this function
///
/// - [`full_f`]: fallible version.
/// - [`TensorAny::full_like`] / [`TensorAny::full_like_f`]: associated method forms of
///   [`full_like`].
pub fn full<Args, Inp>(param: Args) -> Args::Out
where
    Args: FullAPI<Inp>,
{
    return FullAPI::full(param);
}

