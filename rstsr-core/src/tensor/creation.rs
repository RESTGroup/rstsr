/* #region empty */

pub trait EmptyAPI<Inp> {
    type Out;

    /// # Safety
    ///
    /// This function is unsafe because it creates a tensor with uninitialized.
    unsafe fn empty_f(self) -> Result<Self::Out>;

    /// # Safety
    ///
    /// This function is unsafe because it creates a tensor with uninitialized.
    unsafe fn empty(self) -> Self::Out
    where
        Self: Sized,
    {
        Self::empty_f(self).rstsr_unwrap()
    }
}

/// Uninitialized tensor having a specified shape.
///
/// <div class="warning">
///
/// **Row/Column Major Notice**
///
/// This function behaves differently on default orders ([`RowMajor`] and [`ColMajor`]) of device.
///
/// </div>
///
/// The returned tensor is C-contiguous or F-contiguous according to the device
/// default order (or an explicitly specified `order`). Passing a [`Layout`]
/// instead of a shape pins the exact layout and bypasses this behavior. See
/// [`order_semantics`](crate::order_semantics) for a discussion of the two orders.
///
/// # Overloads Table
///
/// Output is [`Tensor<T, B, IxD>`][`Tensor`].
///
/// - `empty((shape: D, device: &B)) -> Tensor<T, B, IxD>`
/// - `empty((shape: D, order: FlagOrder, device: &B)) -> Tensor<T, B, IxD>`
/// - `empty((layout: Layout<D>, device: &B)) -> Tensor<T, B, IxD>` (use the exact layout)
///
/// Also, overloads without the device argument behave the same and create the
/// tensor on [`DeviceCpu::default()`]:
///
/// - `empty((shape: D, order: FlagOrder)) -> Tensor<T, DeviceCpu, IxD>`
/// - `empty(shape: D) -> Tensor<T, DeviceCpu, IxD>`
/// - `empty(layout: Layout<D>) -> Tensor<T, DeviceCpu, IxD>`
///
/// # Parameters
///
/// - `shape`: shape of the new tensor, anything that converts into [`AxesIndex<isize>`][AxesIndex].
///   - Overloads:
///     - integer: 1-D shape with a single dimension.
///     - vector/array/tuple of integers: N-D shape with N dimensions.
/// - `order`: [`FlagOrder`] ([`RowMajor`] or [`ColMajor`]): contiguity of the new tensor. Defaults
///   to the device default order if omitted.
/// - `layout`: [`Layout<D>`][`Layout`]: exact layout (shape, stride, and offset) of the new tensor.
/// - `device`: the device to create the tensor on.
///
/// # Returns
///
/// - [`Tensor<T, B, IxD>`][`Tensor`]: tensor with uninitialized data.
///
/// # Examples
///
/// The content of the new tensor is arbitrary until it is written:
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(RowMajor);
/// let mut a: Tensor<i32, _> = unsafe { rt::empty(([2, 2], &device)) };
/// a.fill(0);
/// println!("{a}");
/// // [[ 0 0]
/// //  [ 0 0]]
/// # assert_eq!(format!("{a}"), "[[ 0 0]\n [ 0 0]]");
/// ```
///
/// ## Difference between [`RowMajor`] and [`ColMajor`]
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(RowMajor);
/// let a: Tensor<i32, _> = unsafe { rt::empty(([2, 3], &device)) };
/// println!("{:?}", a.layout());
/// // 2-Dim (dyn), contiguous: Cc
/// // shape: [2, 3], stride: [3, 1], offset: 0
/// # assert_eq!(format!("{:?}", a.layout()), "2-Dim (dyn), contiguous: Cc\nshape: [2, 3], stride: [3, 1], offset: 0");
///
/// device.set_default_order(ColMajor);
/// let a: Tensor<i32, _> = unsafe { rt::empty(([2, 3], &device)) };
/// println!("{:?}", a.layout());
/// // 2-Dim (dyn), contiguous: Ff
/// // shape: [2, 3], stride: [1, 2], offset: 0
/// # assert_eq!(format!("{:?}", a.layout()), "2-Dim (dyn), contiguous: Ff\nshape: [2, 3], stride: [1, 2], offset: 0");
/// ```
///
/// # Notes of API accordance
///
/// - Array-API: `empty(shape, /, *, dtype=None, device=None)` ([`empty`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.empty.html))
/// - NumPy: `numpy.empty(shape, dtype=float, order='C')` ([`numpy.empty`](https://numpy.org/doc/stable/reference/generated/numpy.empty.html))
/// - RSTSR: `rt::empty((shape, order, &device))`; the dtype is inferred from the type annotation or
///   usage, and `order` participates in the tuple overload.
///
/// # Safety
///
/// This function is unsafe because it creates a tensor with uninitialized
/// underlying data. Reading elements before writing them is undefined behavior.
///
/// For a safe alternative, use [`zeros`].
///
/// # Panics
///
/// - Panics if the provided [`Layout`] is invalid (out-of-bound bounds).
///
/// For a fallible version, use [`empty_f`].
///
/// # See also
///
/// ## Similar function from other crates/libraries
///
/// - Python Array API standard: [`empty`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.empty.html)
/// - NumPy: [`numpy.empty`](https://numpy.org/doc/stable/reference/generated/numpy.empty.html)
///
/// ## Related functions in RSTSR
///
/// - [`empty_like`]: uninitialized tensor with the shape of another tensor.
/// - [`uninit`]: uninitialized tensor of [`MaybeUninit`], initialized later by [`assume_init`].
/// - [`zeros`]: safe alternative, filled with zeros.
///
/// ## Variants of this function
///
/// - [`empty_f`]: fallible version.
pub unsafe fn empty<Args, Inp>(param: Args) -> Args::Out
where
    Args: EmptyAPI<Inp>,
{
    return EmptyAPI::empty(param);
}

/// Uninitialized tensor having a specified shape.
///
/// See also [`empty`].
///
/// # Safety
///
/// This function is unsafe because it creates a tensor with uninitialized.
pub unsafe fn empty_f<Args, Inp>(param: Args) -> Result<Args::Out>
where
    Args: EmptyAPI<Inp>,
{
    return EmptyAPI::empty_f(param);
}

impl<T, D, B> EmptyAPI<(T, D)> for (Layout<D>, &B)
where
    D: DimAPI,
    B: DeviceAPI<T> + DeviceCreationAnyAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    unsafe fn empty_f(self) -> Result<Self::Out> {
        let (layout, device) = self;
        let (_, idx_max) = layout.bounds_index()?;
        let storage = B::empty_impl(device, idx_max)?;
        unsafe { Ok(Tensor::new_unchecked(storage, layout.into_dim()?)) }
    }
}

impl<T, D, B> EmptyAPI<(T, D)> for (D, FlagOrder, &B)
where
    D: DimAPI,
    B: DeviceAPI<T> + DeviceCreationAnyAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    unsafe fn empty_f(self) -> Result<Self::Out> {
        let (shape, order, device) = self;
        let layout = shape.new_contig(None, order);
        empty_f((layout, device))
    }
}

impl<T, D, B> EmptyAPI<(T, D)> for (D, &B)
where
    D: DimAPI,
    B: DeviceAPI<T> + DeviceCreationAnyAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    unsafe fn empty_f(self) -> Result<Self::Out> {
        let (shape, device) = self;
        let default_order = device.default_order();
        let layout = shape.new_contig(None, default_order);
        empty_f((layout, device))
    }
}

impl<T, D> EmptyAPI<(T, D)> for (D, FlagOrder)
where
    D: DimAPI,
{
    type Out = Tensor<T, DeviceCpu, IxD>;

    unsafe fn empty_f(self) -> Result<Self::Out> {
        let (shape, order) = self;
        empty_f((shape, order, &DeviceCpu::default()))
    }
}

