pub trait ArangeAPI<Inp> {
    type Out;

    fn arange_f(self) -> Result<Self::Out>;

    fn arange(self) -> Self::Out
    where
        Self: Sized,
    {
        Self::arange_f(self).rstsr_unwrap()
    }
}

/// Evenly spaced values within the half-open interval `[start, stop)` as a
/// one-dimensional tensor.
///
/// Values are generated by repeatedly adding `step` to `start` until `stop` is
/// reached (or passed), following the same convention as NumPy. A descending
/// interval is generated by a negative `step`.
///
/// This function behaves identically under [`RowMajor`] and [`ColMajor`] device default orders.
///
/// # Overloads Table
///
/// Output is always [`Tensor<T, B, IxD>`][`Tensor`] (one-dimensional, owned data).
///
/// - `arange((start: T, stop: T, step: T, device: &B)) -> Tensor<T, B, IxD>`
/// - `arange((start: T, stop: T, device: &B)) -> Tensor<T, B, IxD>` (implicit `step = 1`)
/// - `arange((stop: T, device: &B)) -> Tensor<T, B, IxD>` (implicit `start = 0`, `step = 1`)
///
/// Also, overloads without the device argument behave the same and create the
/// tensor on [`DeviceCpu::default()`]:
///
/// - `arange((start: T, stop: T, step: T)) -> Tensor<T, DeviceCpu, IxD>`
/// - `arange((start: T, stop: T)) -> Tensor<T, DeviceCpu, IxD>`
/// - `arange(stop: T) -> Tensor<T, DeviceCpu, IxD>`
///
/// # Parameters
///
/// - `start`: starting value of the interval; defaults to `0` if omitted.
/// - `stop`: end of the interval (exclusive).
/// - `step`: spacing between values; defaults to `1` if omitted; must not be zero.
/// - `device`: the device to create the tensor on.
///
/// # Returns
///
/// - [`Tensor<T, B, IxD>`][`Tensor`]: one-dimensional tensor of evenly spaced values, owning its
///   data.
///
/// # Examples
///
/// ```rust
/// # use rstsr::prelude::*;
/// println!("{}", rt::arange(5));
/// // [ 0 1 2 3 4]
/// ```
///
/// Start, stop, and step can all be specified; a negative step generates a
/// descending interval:
///
/// ```rust
/// # use rstsr::prelude::*;
/// println!("{}", rt::arange((2, 10)));
/// // [ 2 3 4 5 6 7 8 9]
/// println!("{}", rt::arange((10, 0, -3)));
/// // [ 10 7 4 1]
/// ```
///
/// With an explicit device:
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let device = DeviceCpu::default();
/// let a = rt::arange((5, &device));
/// println!("{a}");
/// // [ 0 1 2 3 4]
/// # assert_eq!(a.shape(), &[5]);
/// ```
///
/// # Notes of API accordance
///
/// - Array-API: `arange(start, /, stop, step=1)` ([`arange`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.arange.html))
/// - NumPy: `numpy.arange([start, ]stop, [step, ])` ([`numpy.arange`](https://numpy.org/doc/stable/reference/generated/numpy.arange.html))
/// - RSTSR: `rt::arange((start, stop, step, &device))`; the arguments are grouped into one tuple
///   instead of a fixed signature.
///
/// Please note that, unlike NumPy, this function always returns a one-dimensional
/// tensor; combine with [`reshape`] or [`into_shape`] for higher dimensionality.
///
/// # Panics
///
/// - Panics if `step` is zero.
///
/// For a fallible version, use [`arange_f`].
///
/// # See also
///
/// ## Similar function from other crates/libraries
///
/// - Python Array API standard: [`arange`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.arange.html)
/// - NumPy: [`numpy.arange`](https://numpy.org/doc/stable/reference/generated/numpy.arange.html)
///
/// ## Related functions in RSTSR
///
/// - [`linspace`]: evenly spaced numbers over an interval, by number of points.
/// - [`reshape`]: change the shape of the generated tensor.
///
/// ## Variants of this function
///
/// - [`arange_f`]: fallible version.
pub fn arange<Args, Inp>(param: Args) -> Args::Out
where
    Args: ArangeAPI<Inp>,
{
    return ArangeAPI::arange(param);
}

/// Evenly spaced values within the half-open interval `[start, stop)` as a one-dimensional tensor.
///
/// See also [`arange`].
pub fn arange_f<Args, Inp>(param: Args) -> Result<Args::Out>
where
    Args: ArangeAPI<Inp>,
{
    return ArangeAPI::arange_f(param);
}

impl<T, B> ArangeAPI<(T, B)> for (T, T, T, &B)
where
    B: DeviceAPI<T> + DeviceCreationArangeAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // full implementation
        let (start, stop, step, device) = self;
        let data = device.arange_impl(start, stop, step)?;
        let layout = vec![data.len()].into();
        unsafe { Ok(Tensor::new_unchecked(data, layout)) }
    }
}

impl<T, B> ArangeAPI<(T, B)> for (T, T, &B)
where
    T: One,
    B: DeviceAPI<T> + DeviceCreationArangeAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // (start, stop, device) -> (start, stop, 1, device)
        let (start, stop, device) = self;
        let step = T::one();
        arange_f((start, stop, step, device))
    }
}

impl<T, B> ArangeAPI<(T, B)> for (T, &B)
where
    T: Zero + One,
    B: DeviceAPI<T> + DeviceCreationArangeAPI<T>,
{
    type Out = Tensor<T, B, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // (stop, device) -> (0, stop, 1, device)
        let (stop, device) = self;
        let start = T::zero();
        let step = T::one();
        arange_f((start, stop, step, device))
    }
}

impl<T> ArangeAPI<T> for (T, T, T)
where
    T: PartialOrd + Clone + Add<Output = T> + Zero + 'static,
{
    type Out = Tensor<T, DeviceCpu, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // full implementation
        let (start, stop, step) = self;
        arange_f((start, stop, step, &DeviceCpu::default()))
    }
}

impl<T> ArangeAPI<T> for (T, T)
where
    T: PartialOrd + Clone + Add<Output = T> + Zero + One + 'static,
{
    type Out = Tensor<T, DeviceCpu, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // (start, stop) -> (start, stop, 1)
        let (start, stop) = self;
        arange_f((start, stop, &DeviceCpu::default()))
    }
}

impl<T> ArangeAPI<T> for T
where
    T: PartialOrd + Clone + Add<Output = T> + Zero + One + 'static,
{
    type Out = Tensor<T, DeviceCpu, IxD>;

    fn arange_f(self) -> Result<Self::Out> {
        // (stop) -> (0, stop, 1)
        arange_f((T::zero(), self, &DeviceCpu::default()))
    }
}

