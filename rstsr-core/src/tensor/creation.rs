///
/// - `ones((shape: D, device: &B)) -> Tensor<T, B, IxD>`
/// - `ones((shape: D, order: FlagOrder, device: &B)) -> Tensor<T, B, IxD>`
/// - `ones((layout: Layout<D>, device: &B)) -> Tensor<T, B, IxD>` (use the exact layout)
///
/// Also, overloads without the device argument behave the same and create the
/// tensor on [`DeviceCpu::default()`]:
///
/// - `ones((shape: D, order: FlagOrder)) -> Tensor<T, DeviceCpu, IxD>`
/// - `ones(shape: D) -> Tensor<T, DeviceCpu, IxD>`
/// - `ones(layout: Layout<D>) -> Tensor<T, DeviceCpu, IxD>`
