/// );
/// println!("{tsr:?}");
/// // [[ 1 2 3]
/// //  [ 4 5 6]]
/// // 2-Dim (dyn), contiguous: Cc
///
/// let tsr = rt::tensor_from_nested!(
///     [[[1, 2],
///       [3, 4]],
///      [[5, 6],
///       [7, 8]]]
