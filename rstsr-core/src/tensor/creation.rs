/// Uninitialized tensor with the same shape as an input tensor.
///
/// This function behaves identically under [`RowMajor`] and [`ColMajor`] device default orders.
///
/// The output layout is controlled by `order` (a [`TensorIterOrder`]), which
/// defaults to [`TensorIterOrder::K`]: the axis order of the input layout is
/// kept as far as possible (similar to NumPy's `order='K'`). This behavior
/// depends only on the input layout, not on the device default order.
///
/// # Overloads Table
///
/// Output is [`Tensor<T, B, D>`][`Tensor`] (same shape as the input tensor).
///
/// - `empty_like(tensor: &TensorAny<R, T, B, D>) -> Tensor<T, B, D>` (implicit `order = K`, device
///   of input)
/// - `empty_like((tensor: &TensorAny<R, T, B, D>, order: TensorIterOrder)) -> Tensor<T, B, D>`
/// - `empty_like((tensor: &TensorAny<R, T, B, D>, device: &B)) -> Tensor<T, B, D>`
/// - `empty_like((tensor: &TensorAny<R, T, B, D>, order: TensorIterOrder, device: &B)) -> Tensor<T,
///   B, D>`
///
/// # Parameters
///
/// - `tensor`: the input tensor; the output shares its shape.
/// - `order`: [`TensorIterOrder`] controlling the output layout; defaults to
///   [`TensorIterOrder::K`].
/// - `device`: the device to create the tensor on; defaults to the device of `tensor` if omitted.
///
/// # Returns
///
/// - [`Tensor<T, B, D>`][`Tensor`]: tensor with uninitialized data.
///
/// # Examples
///
/// ```rust
/// # use rstsr::prelude::*;
/// # let mut device = DeviceCpu::default();
/// # device.set_default_order(RowMajor);
/// let a = rt::arange((6, &device)).into_shape([2, 3]);
/// let mut b = unsafe { rt::empty_like((&a, &device)) };
/// b.fill(0);
/// println!("{b}");
/// // [[ 0 0 0]
/// //  [ 0 0 0]]
/// # assert_eq!(b.shape(), a.shape());
/// ```
///
/// # Notes of API accordance
///
/// - Array-API: `empty_like(x, /, *, dtype=None, device=None)` ([`empty_like`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.empty_like.html))
/// - NumPy: `numpy.empty_like(prototype, dtype=None, order='K', subok=True)` ([`numpy.empty_like`](https://numpy.org/doc/stable/reference/generated/numpy.empty_like.html))
/// - RSTSR: `rt::empty_like((tensor, order, &device))`; the dtype is always kept from the input
///   tensor, and `order` participates in the tuple overload.
///
/// # Safety
///
/// This function is unsafe because it creates a tensor with uninitialized
/// underlying data. Reading elements before writing them is undefined behavior.
///
/// # Panics
///
/// - Panics if `order` is not one of the copy-supported iteration orders ([`TensorIterOrder::C`],
///   [`TensorIterOrder::F`], [`TensorIterOrder::A`], [`TensorIterOrder::K`]).
///
/// For a fallible version, use [`empty_like_f`].
///
/// # See also
///
/// ## Similar function from other crates/libraries
///
/// - Python Array API standard: [`empty_like`](https://data-apis.org/array-api/2024.12/API_specification/generated/array_api.empty_like.html)
/// - NumPy: [`numpy.empty_like`](https://numpy.org/doc/stable/reference/generated/numpy.empty_like.html)
///
/// ## Related functions in RSTSR
///
/// - [`empty`]: uninitialized tensor by shape.
/// - [`zeros_like`]: safe alternative, filled with zeros.
///
/// ## Variants of this function
///
/// - [`empty_like_f`]: fallible version.
pub unsafe fn empty_like<Args, Inp>(param: Args) -> Args::Out
where
    Args: EmptyLikeAPI<Inp>,
{
    return EmptyLikeAPI::empty_like(param);
}

/// Uninitialized tensor with the same shape as an input tensor.
///
/// See also [`empty_like`].
///
