/// Evenly spaced numbers over a specified interval.
///
/// `num` samples are generated over the closed interval `[start, stop]`
/// (when `endpoint` is true, the default) or over `[start, stop)` otherwise.
/// For boundary conditions, the current implementation is similar to NumPy,
/// where `num = 0` will return an empty tensor, and `num = 1` will return a
/// tensor with the starting value.
///
/// This function behaves identically under [`RowMajor`] and [`ColMajor`] device default orders.
///
/// # Overloads Table
///
/// Output is [`Tensor<T, B, IxD>`][`Tensor`] (one-dimensional, owned data); `T`
/// must be a float or complex type ([`ComplexFloat`]).
///
/// - `linspace((start: T, stop: T, num: usize, endpoint: bool, device: &B)) -> Tensor<T, B, IxD>`
/// - `linspace((start: T, stop: T, num: usize, device: &B)) -> Tensor<T, B, IxD>` (implicit
///   `endpoint = true`)
///
/// Also, overloads without the device argument behave the same and create the
/// tensor on [`DeviceCpu::default()`]:
///
/// - `linspace((start: T, stop: T, num: usize, endpoint: bool)) -> Tensor<T, DeviceCpu, IxD>`
/// - `linspace((start: T, stop: T, num: usize)) -> Tensor<T, DeviceCpu, IxD>`
///
/// # Parameters
///
/// - `start`: starting value of the interval.
/// - `stop`: end value of the interval, unless `endpoint` is false.
/// - `num`: number of samples to generate.
/// - `endpoint`: if true (default), `stop` is the last sample; if false, `stop` is excluded.
/// - `device`: the device to create the tensor on.
///
/// # Returns
